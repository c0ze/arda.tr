/**
 * Publishes the family's brand files and their contract.
 *
 * The Index (see DESIGN.md) is shared by arda.tr, blog.arda.tr, resume.arda.tr
 * and ai.arda.tr as four files in brand/: arda.css and arda.js (the built
 * Astryx theme: its stylesheet, and the module React sites pass to <Theme>),
 * brand.css (the family patterns) and scheme.js (the scheme switch). The
 * sibling sites carry verbatim copies of the ones they use; their CI fetches
 * config/themes.json from this repository and compares hashes.
 *
 * This script copies the built theme into brand/ and writes the contract (v4).
 * It only uses node built-ins, so CI can run it without `npm ci`.
 */
import { createHash } from "node:crypto";
import { promises as fs } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const projectRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const builtDir = path.join(projectRoot, "themes", "arda");
const brandDir = path.join(projectRoot, "brand");
const outputFile = path.join(projectRoot, "config", "themes.json");

/** The files a sibling site must carry unchanged. */
export const BRAND_FILES = ["arda.css", "arda.js", "brand.css", "scheme.js"];

/** The ones built by `astryx experimental theme compile` in themes/arda/. */
const BUILT_FILES = ["arda.css", "arda.js", "arda.d.ts", "arda.variants.d.ts"];

const sha256 = (buffer) => createHash("sha256").update(buffer).digest("hex");

export async function buildContract() {
  // brand/ holds the copies the family reads.
  for (const name of BUILT_FILES) {
    await fs.copyFile(path.join(builtDir, name), path.join(brandDir, name));
  }

  const files = {};
  for (const name of BRAND_FILES) {
    files[name] = { sha256: sha256(await fs.readFile(path.join(brandDir, name))) };
  }

  return {
    $comment:
      "Generated by scripts/generate-themes-contract.mjs from brand/. Do not hand-edit.",
    version: 4,
    system: "The Index",
    theme: "arda",
    schemes: ["light", "dark"],
    source: "https://raw.githubusercontent.com/c0ze/arda.tr/main/brand/",
    files,
  };
}

async function main() {
  const contract = await buildContract();
  await fs.writeFile(outputFile, `${JSON.stringify(contract, null, 2)}\n`);
  console.log(`Theme contract generated at ${outputFile} (${BRAND_FILES.length} files).`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((error) => {
    console.error(error);
    process.exitCode = 1;
  });
}
